// admin-menu.js — у админа в боте кнопки всех ролей, чтобы проверять, что
// видит РОП, логист, агент или водитель, не заводя себе чужую роль.
//
//   • кнопки РОПа и логистики работают сразу — они по всему отделу;
//   • кнопки агента и водителя привязаны к человеку: бот спрашивает, за кого
//     смотреть, и запоминает выбор до «🔁 Сменить агента/водителя».
//
// Внимание: «📩 Претензия за клиента» от имени выбранного агента создаёт
// настоящую претензию — для проверки её потом нужно удалить в Hub.

const SWITCH = '🔁 Сменить агента/водителя';

const ADMIN_MENU = [
  ['📊 Сводка отдела', '👥 По агентам'],          // как РОП
  ['🚫 Не заказали', '📉 Сигналы'],
  ['🚚 Доставки сегодня', '📋 Итог дня'],         // как логистика
  ['📊 По экспедиторам', '⚙️ Напоминания'],
  ['👥 Мои клиенты', '📩 Претензия за клиента'],  // как агент (спросит, какой)
  ['🚚 Мои доставки', SWITCH],                    // как водитель (спросит, какой)
  ['🔄 Синхронизация', '👤 Telegram-сотрудники'], // свои, админские
];

// Какая роль обрабатывает кнопку, когда её нажимает админ.
const ROUTE = {
  '📊 Сводка отдела': 'head_of_sales',
  '👥 По агентам': 'head_of_sales',
  '📉 Сигналы': 'head_of_sales',
  '🚚 Доставки сегодня': 'logistics',
  '📊 По экспедиторам': 'logistics',
  '📋 Итог дня': 'logistics',
  '⚙️ Напоминания': 'logistics',
  '👥 Мои клиенты': 'agent',
  '📩 Претензия за клиента': 'agent',
  '🚚 Мои доставки': 'expeditor',
};

// Кнопки, привязанные к человеку. Номер кнопки в этом списке уходит в
// callback_data: сама надпись с эмодзи туда не влезает по длине.
const BOUND = ['👥 Мои клиенты', '📩 Претензия за клиента', '🚚 Мои доставки'];

// Список людей кнопками: «за кого смотреть». Telegram ограничивает callback_data
// 64 байтами — длинные id не пропускаем, чтобы не уронить всю клавиатуру.
function pickerKeyboard(kind, people, button) {
  const idx = BOUND.indexOf(button);
  const rows = [];
  for (const p of people.slice(0, 60)) {
    const data = `admas:${kind}:${idx}:${p.id}`;
    if (Buffer.byteLength(data) > 64) continue;
    rows.push([{ text: p.name || String(p.id), callback_data: data }]);
  }
  return { inline_keyboard: rows };
}

// Разбор нажатия из списка. null — не наше или испорчено.
function parsePick(data) {
  const m = String(data || '').match(/^admas:(agent|expeditor):(\d+):(.+)$/);
  if (!m) return null;
  const button = BOUND[Number(m[2])];
  if (!button || ROUTE[button] !== m[1]) return null;
  return { kind: m[1], button, id: m[3] };
}

module.exports = { ADMIN_MENU, ROUTE, BOUND, SWITCH, pickerKeyboard, parsePick };
