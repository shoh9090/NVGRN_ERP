// wipe-guard.js — полные очистки («для тестов») запрещены на рабочей базе.
//
// В Складе, Кассе и Админке есть кнопки, которые стирают весь реестр движений,
// все транзакции или все справочники. Они были нужны при запуске, пока в базе
// лежали тестовые данные. Теперь база рабочая, а одно неверное нажатие админа
// стирает всё без возможности восстановить из приложения (аудит A15).
//
// На Railway (рабочая среда) очистка отказывает. Если когда-нибудь понадобится
// осознанно — временно поставить переменную ALLOW_WIPE=1 в Railway, сделать и убрать.
// Точечные исправления делаются адресно: отмена документа, корректировка, сверка.

function wipeBlocked(env = process.env) {
  const prod = env.NODE_ENV === 'production' || !!env.RAILWAY_ENVIRONMENT;
  if (!prod || env.ALLOW_WIPE === '1') return null;
  return 'Полная очистка отключена на рабочей базе: она стирает реальные данные без возможности восстановить. '
    + 'Исправляйте адресно — отменой документа, корректировкой или сверкой.';
}

module.exports = { wipeBlocked };
