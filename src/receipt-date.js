// receipt-date.js — ОДНО определение «когда поставка относится к месяцу».
//
// Зачем отдельный модуль. В заявке Закупа есть три разные даты, и их легко
// перепутать — а стоит это миллионами в прибыли месяца:
//
//   delivery_date            — ПЛАНОВАЯ дата поставки, когда договорились привезти;
//   received_at              — ВРЕМЯ НАЖАТИЯ КНОПКИ «принял» в ERP. Это запись в
//                              журнале, а не факт поставки: зелень пришла в
//                              субботу, кладовщик отметил во вторник — здесь будет
//                              вторник;
//   delivery_confirmed_date  — ПОДТВЕРЖДЁННАЯ дата поставки: когда товар пришёл
//                              физически, по документу поставщика. Вносит человек
//                              после проверки, с записью в журнал.
//
// Период учёта определяется так: подтверждённая дата → отметка приёмки →
// плановая дата. Пока закупщик не подтвердил дату, поведение остаётся тем же,
// что было: автоматически переносить старые заявки на плановую дату нельзя
// (решение Шоха 01.10.2026) — иначе цифры закрытых месяцев поменяются сами.
//
// Это выражение обязаны использовать ВСЕ: P&L, долг поставщику, взаиморасчёты,
// склад, цены сырья в Калькуляции. Если где-то останется своя пара дат, два
// отчёта про одну поставку покажут разные месяцы — ровно это и случилось с
// августом 2026.
const receiptDate = (alias = 'po') =>
  `COALESCE(${alias}.delivery_confirmed_date, ${alias}.received_at::date, ${alias}.delivery_date)`;

// Готовая строка для самого частого случая (алиас po).
const RECEIPT_DATE = receiptDate('po');

// Почему дата именно такая — для показа человеку рядом с цифрой.
function receiptDateSource(row) {
  if (!row) return null;
  if (row.delivery_confirmed_date) return { source: 'confirmed', label: 'подтверждена закупщиком' };
  if (row.received_at) return { source: 'marked', label: 'по отметке приёмки в ERP (может отличаться от дня поставки)' };
  if (row.delivery_date) return { source: 'plan', label: 'по плановой дате поставки — приёмку не отмечали' };
  return { source: 'none', label: 'даты нет вовсе' };
}

module.exports = { receiptDate, RECEIPT_DATE, receiptDateSource };
