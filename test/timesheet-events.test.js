// Отпуска и больничные из табеля попадают в кадровую историю отрезками.
// Ошибка здесь либо разорвёт один отпуск на пятнадцать записей, либо склеит
// два разных периода в один — и в истории человека будет неправда.
const { test } = require('node:test');
const assert = require('node:assert');
const { dateRuns } = require('../src/hr');

test('подряд идущие дни — один отрезок', () => {
  const r = dateRuns(['2026-09-08', '2026-09-09', '2026-09-10']);
  assert.deepStrictEqual(r, [{ from: '2026-09-08', to: '2026-09-10' }]);
});

test('один день — отрезок из самого себя', () => {
  assert.deepStrictEqual(dateRuns(['2026-09-08']), [{ from: '2026-09-08', to: '2026-09-08' }]);
});

test('разрыв в днях разделяет отрезки', () => {
  // Болел 2–3, вышел, снова болел 7-го: это две записи, а не «с 2 по 7».
  const r = dateRuns(['2026-09-02', '2026-09-03', '2026-09-07']);
  assert.deepStrictEqual(r, [
    { from: '2026-09-02', to: '2026-09-03' },
    { from: '2026-09-07', to: '2026-09-07' },
  ]);
});

test('переход через границу месяца не рвёт отрезок', () => {
  const r = dateRuns(['2026-08-31', '2026-09-01']);
  assert.deepStrictEqual(r, [{ from: '2026-08-31', to: '2026-09-01' }]);
});

test('пустой список — пусто', () => {
  assert.deepStrictEqual(dateRuns([]), []);
});
