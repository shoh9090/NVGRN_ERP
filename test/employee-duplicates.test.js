// Похожие ФИО при заведении новой карточки. Один человек двумя карточками —
// самая дорогая ошибка в Кадрах: табель ведётся на одной, зарплата считается
// на двух. Но и переспрашивать на каждом однофамильце нельзя — начнут жать
// «это новый» не читая, и смысл проверки пропадёт.
const { test } = require('node:test');
const assert = require('node:assert');
const { sameName } = require('../src/hr');

test('то же имя с отчеством и без — похоже', () => {
  assert.ok(sameName('Каримова Висола', 'Каримова Висола Бахтияровна'));
  assert.ok(sameName('Каримова Висола Бахтияровна', 'Каримова Висола'));
});

test('одно имя внутри полного — похоже', () => {
  assert.ok(sameName('Азиза', 'Мурадова Азиза'));
});

test('порядок слов не важен', () => {
  assert.ok(sameName('Висола Каримова', 'Каримова Висола'));
});

test('регистр, ё и лишние пробелы не мешают', () => {
  assert.ok(sameName('  СЕМЁНОВА   Анна ', 'Семенова Анна'));
});

test('однофамильцы с разными именами — не похоже', () => {
  assert.ok(!sameName('Каримова Висола', 'Каримова Дилноза'));
});

test('разные люди — не похоже', () => {
  assert.ok(!sameName('Иванова Мария', 'Петрова Ольга'));
});

test('пустое ФИО ни с чем не совпадает', () => {
  assert.ok(!sameName('', 'Иванова Мария'));
  assert.ok(!sameName('Иванова Мария', '   '));
});

test('короткие куски (инициалы, «оглы») сходства не создают', () => {
  // Иначе «Ким А.» совпал бы с любым, у кого есть слово из двух букв.
  assert.ok(!sameName('Ким А.', 'Ли А.'));
});
