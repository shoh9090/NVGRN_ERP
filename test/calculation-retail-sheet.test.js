// Сверка расчёта с настоящим листом «0000_розница» из файла Шоха (розн.xlsx).
// Все ожидаемые числа взяты прямо из ячеек Excel, все восемь товаров.
// Если кто-то поправит формулу «на глаз» — тест покажет расхождение с рабочим
// файлом, по которому Шох принимает решения о ценах.
const test = require('node:test');
const assert = require('node:assert');
const { skuEconomics } = require('../src/calculation-engine');

const PACK = 1007.25;                       // комплект «вак.пакет розница»
const PROD = 5594.0559440559446;            // производ.затраты на штуку

// В себестоимость на товарных листах входят ТОЛЬКО эти три составляющие:
// с/с = зелень в упаковке + упаковка + производ.затраты (в Excel — сумма
// ячеек E6;E8;E9). ФОТ показан отдельной строкой и в с/с не входит.
const COMPONENTS = { components: ['pack', 'raw', 'production'] };

// name, граммаж, цена за кг, доля произв.затрат, брак %, цена 1
const ITEMS = [
  ['Латук 100г', 100, 17000, 0, 50, 21000],
  ['романо 100г', 100, 20000, 1, 50, 24000],
  ['рукола 100г', 100, 30000, 0.5, 50, 20800],
  ['шпинат 100г', 100, 25000, 1, 50, 29800],
  ['кейл 100г', 100, 35000, 1, 50, 25500],
  ['мангольд 100г', 100, 50000, 1, 20, 22400],
  ['лоло-россо 100г', 100, 17000, 1, 50, 28600],
  ['айсберг 150г', 150, 12000, 1, 50, 20500],
];

// Значения из ячеек Excel: зелень (R6), с/с (R12), с/с с браком (R13),
// наценка (R15), прибыль (R20), чистая прибыль (R22), ЧП % (R23).
const EXCEL = {
  'Латук 100г': [1700, 2707.25, 4060.875, 4.171299288946348, 10009.125, 8507.75625, 0.40513125],
  'романо 100г': [2000, 8601.3059440559446, 12901.958916083917, 0.86018264017884727, 3178.0410839160832, 2701.3349213286706, 0.11255562172202795],
  'рукола 100г': [3000, 6804.2779720279723, 10206.416958041958, 1.0379335946696773, 3729.5830419580416, 3170.1455856643352, 0.15241084546463149],
  'шпинат 100г': [2500, 9101.3059440559446, 13651.958916083917, 1.1828369234902572, 6314.0410839160832, 5366.9349213286705, 0.18009848729290839],
  'кейл 100г': [3500, 10101.305944055945, 15151.958916083917, 0.68295070896288923, 1933.0410839160832, 1643.0849213286706, 0.064434702797202772],
  'мангольд 100г': [5000, 11601.305944055945, 13921.567132867134, 0.60901425724667968, 1086.4328671328658, 923.4679370629359, 0.041226247190309637],
  'лоло-россо 100г': [1700, 8301.3059440559446, 12451.958916083917, 1.296827366098841, 6710.0410839160832, 5703.5349213286709, 0.19942429794855493],
  'айсберг 150г': [1800, 8401.3059440559446, 12601.958916083917, 0.62673121984517732, 1133.0410839160832, 963.0849213286707, 0.046979752259935156],
};

const EPS = 0.005;   // полтийина

for (const [name, weightG, pricePerKg, factor, defect, price] of ITEMS) {
  test('лист «0000_розница»: ' + name, () => {
    // Зелень в упаковке считается как в Excel: граммаж / 1000 × цена за кг
    const raw = (weightG / 1000) * pricePerKg;
    const r = skuEconomics({
      pack: PACK, raw, production: PROD * factor,
      defect_pct: defect, price, retro_pct: 21, vat_pct: 12, profit_tax_pct: 15,
    }, COMPONENTS);

    const [xRaw, xCost, xDefect, xMarkup, xProfit, xNet, xNetPct] = EXCEL[name];
    const near = (got, want, what) =>
      assert.ok(Math.abs(got - want) < EPS, what + ': у нас ' + got + ', в Excel ' + want);

    near(raw, xRaw, 'зелень в упаковке');
    near(r.cost, xCost, 'с/с');
    near(r.cost_defect, xDefect, 'с/с с браком');
    near(r.markup_pct / 100, xMarkup, 'наценка');
    near(r.profit, xProfit, 'прибыль');
    near(r.net_profit, xNet, 'чистая прибыль');
    near(r.net_pct / 100, xNetPct, 'ЧП %');

    // ФОТ в себестоимость не входит — его нет среди компонентов
    assert.strictEqual(r.components.labor, undefined);
  });
}

test('ФОТ не влияет на себестоимость товарного листа', () => {
  const base = { pack: PACK, raw: 2000, production: PROD, defect_pct: 50, price: 24000 };
  const без = skuEconomics(base, COMPONENTS);
  const с = skuEconomics({ ...base, labor: 5594.06 }, COMPONENTS);
  assert.strictEqual(с.cost, без.cost);
});
