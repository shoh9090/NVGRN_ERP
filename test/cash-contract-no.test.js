// Номер договора из назначения платежа. У одного юрлица бывает несколько
// торговых точек, долг в CRM ведётся по точке, и именно номер договора
// говорит, чья это оплата. Ошибка здесь засчитает деньги не той точке:
// у одной появится переплата, у другой — долг.
const { test } = require('node:test');
const assert = require('node:assert');
const { contractNo } = require('../src/cash');

test('узбекское назначение: «182-сонли шартнома»', () => {
  assert.strictEqual(
    contractNo('0009820.08.2026 даги 182-сонли шартномага асосан тулов утказилмокда'), '182');
  assert.strictEqual(
    contractNo('0009816.06.2026 даги 147-сонли шартномага асосан тулов утказилмокда'), '147');
});

test('русское назначение: «по дог № 51»', () => {
  assert.strictEqual(contractNo('00098 оплата по дог № 51 от 02.01.2026 г за Микрозелень'), '51');
  assert.strictEqual(contractNo('Оплата по договору 147 за зелень'), '147');
  assert.strictEqual(contractNo('оплата по договору №7 от 01.09'), '7');
});

test('латиницей: shartnoma', () => {
  assert.strictEqual(contractNo('to`lov shartnoma 214 asosida'), '214');
});

test('номера договора нет — честно null', () => {
  // Пусто лучше, чем угаданный номер: на нём посадят деньги не той точке.
  assert.strictEqual(contractNo('Оплата за товар'), null);
  assert.strictEqual(contractNo(''), null);
  assert.strictEqual(contractNo(null), null);
});

test('дата в назначении не путается с номером договора', () => {
  // В строке полно цифр — дата, номер платёжки. Берём только то, что стоит
  // рядом со словом «договор» или «сонли».
  assert.strictEqual(
    contractNo('0009820.08.2026 даги 182-сонли шартномага асосан'), '182');
});
